"""Bounded, single-host Laravel autoscaler using the local Docker CLI."""

import json
import ipaddress
import logging
import os
from functools import lru_cache
from pathlib import Path
import subprocess
import sys
import time


SERVICE = "app"
NGINX = "laravel_nginx"
UPSTREAM = Path("/etc/nginx/autoscaling/laravel-upstream.conf")
STATUS = Path("/etc/nginx/autoscaling/status.json")
HEARTBEAT = Path("/tmp/autoscaler-heartbeat")
LOG = logging.getLogger("autoscaler")


def docker(*args, timeout=45):
    result = subprocess.run(
        ["docker", *args], capture_output=True, text=True, timeout=timeout
    )
    if result.returncode:
        raise RuntimeError(f"docker {' '.join(args)}: {result.stderr.strip()}")
    return result.stdout.strip()


def state(name):
    return json.loads(docker("inspect", "--format", "{{json .State}}", name))


def healthy(value):
    return value.get("Running", False) and value.get("Health", {}).get("Status") == "healthy"


@lru_cache(maxsize=1)
def context():
    """Discover the actual Compose project and checkout from our own container."""
    own = json.loads(docker("inspect", os.environ["HOSTNAME"]))[0]
    project = own["Config"]["Labels"]["com.docker.compose.project"]
    directory = next(mount["Source"] for mount in own["Mounts"]
                     if mount["Destination"] == "/workspace")
    return project, directory


def replicas():
    project, _ = context()
    ids = docker("ps", "--all", "--filter", f"label=com.docker.compose.project={project}",
                 "--filter", f"label=com.docker.compose.service={SERVICE}",
                 "--filter", "label=com.docker.compose.oneoff=False", "--format", "{{.ID}}").split()
    if not ids:
        raise RuntimeError("No Laravel app replicas found; suspending scaling")
    containers = json.loads(docker("inspect", *ids))
    containers.sort(key=lambda value: int(value["Config"]["Labels"]["com.docker.compose.container-number"]))
    numbers = [int(value["Config"]["Labels"]["com.docker.compose.container-number"]) for value in containers]
    if numbers not in ([1], [1, 2]):
        raise RuntimeError(f"Unexpected app replica numbers {numbers}; refusing to change them")
    return containers


def compose_scale(count):
    if count not in (1, 2):
        raise ValueError("Laravel scaling is bounded to one or two replicas")
    project, directory = context()
    docker("compose", "--project-name", project, "--project-directory", directory,
           "--env-file", "/workspace/.env", "-f", "/workspace/docker-compose.yml",
           "up", "-d", "--no-deps", "--no-build", "--pull", "never", "--no-recreate",
           "--scale", f"{SERVICE}={count}", SERVICE, timeout=120)


def cpu_usage(names):
    lines = docker("stats", "--no-stream", "--format", "{{json .}}", *names).splitlines()
    samples = {item["Name"]: float(item["CPUPerc"].rstrip("%"))
               for item in map(json.loads, lines)}
    if set(samples) != set(names):
        raise RuntimeError("Incomplete CPU statistics; skipping scaling decision")
    return sum(samples.values())


def workers():
    lines = docker("top", NGINX, "-eo", "pid,args").splitlines()[1:]
    return {line.split()[0] for line in lines if "nginx: worker process" in line}


def render(containers):
    if len(containers) not in (1, 2):
        raise ValueError("The upstream must contain one or two healthy replicas")
    servers = []
    for container in containers:
        address = ipaddress.ip_address(container["NetworkSettings"]["Networks"]["app-network"]["IPAddress"])
        host = f"[{address}]" if address.version == 6 else str(address)
        servers.append(f"    server {host}:9000; # {container['Name'].lstrip('/')}\n")
    return ("# Generated by laravel_autoscaler from current Docker replica addresses.\n"
            "upstream laravel_upstream {\n" + "".join(servers)
            + "}\n")


def atomic_write(value):
    temporary = UPSTREAM.with_suffix(".tmp")
    temporary.write_text(value)
    temporary.chmod(0o644)
    temporary.replace(UPSTREAM)


def route(containers):
    """Validate, reload, and confirm a new worker generation before proceeding."""
    desired = render(containers)
    previous = UPSTREAM.read_text()
    if previous == desired:
        return set()
    old_workers = workers()
    atomic_write(desired)
    try:
        docker("exec", NGINX, "nginx", "-t")
        docker("exec", NGINX, "nginx", "-s", "reload")
        deadline = time.monotonic() + 15
        while time.monotonic() < deadline:
            if workers() - old_workers:
                LOG.info("Nginx now routes new requests to %s Laravel replica(s)", len(containers))
                return old_workers
            time.sleep(0.5)
        raise RuntimeError("Nginx did not start a new worker generation")
    except Exception:
        atomic_write(previous)
        docker("exec", NGINX, "nginx", "-t")
        docker("exec", NGINX, "nginx", "-s", "reload")
        raise


def heartbeat():
    HEARTBEAT.write_text(str(time.time()))
    if STATUS.exists():
        try:
            payload = json.loads(STATUS.read_text())
            payload["updated_at"] = time.time()
            atomic_write_status(payload)
        except (OSError, ValueError, TypeError):
            LOG.warning("Could not refresh the autoscaler status timestamp")


def atomic_write_status(payload):
    temporary = STATUS.with_suffix(".tmp")
    temporary.write_text(json.dumps(payload, separators=(",", ":")))
    temporary.chmod(0o644)
    temporary.replace(STATUS)


def wait_replicas(count, timeout=120):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        heartbeat()
        containers = replicas()
        if len(containers) == count and all(healthy(value["State"]) for value in containers):
            return containers
        time.sleep(2)
    raise RuntimeError(f"{count} app replicas did not become healthy within {timeout}s")


def scale_up():
    LOG.info("Scaling app service up to two replicas")
    containers = replicas()
    if not healthy(containers[0]["State"]):
        raise RuntimeError("Primary replica unavailable; suspending scale-up")
    compose_scale(2)
    route(wait_replicas(2))


def scale_down():
    containers = replicas()
    if not all(healthy(value["State"]) for value in containers):
        raise RuntimeError("An app replica is unhealthy; suspending scale-down")
    if len(containers) == 1:
        route(containers)
        return True
    primary, secondary = containers
    LOG.info("Scaling down: draining replica %s", secondary["Name"])
    # Include workers left over from earlier reloads: they can use the secondary.
    old_workers = workers()
    old_workers.update(route([primary]))
    deadline = time.monotonic() + 330
    while time.monotonic() < deadline:
        heartbeat()
        if not healthy(state(primary["Id"])):
            route(containers)
            raise RuntimeError("Primary became unhealthy; keeping the secondary running")
        if not old_workers.intersection(workers()):
            # All workers using the previous upstream have finished their requests.
            docker("stop", "--signal", "SIGQUIT", "--timeout", "30", secondary["Id"])
            # Only remove the drained replica container; shared bind mounts remain.
            docker("rm", secondary["Id"])
            LOG.info("Scaled down to one Laravel instance")
            return True
        time.sleep(2)
    route(containers)
    LOG.warning("Drain exceeded 330s (possibly an open WebSocket); keeping two instances")
    return False


class Policy:
    def __init__(self):
        self.interval = float(os.getenv("AUTOSCALE_INTERVAL", "15"))
        self.up_cpu = float(os.getenv("AUTOSCALE_UP_CPU", "70"))
        self.down_cpu = float(os.getenv("AUTOSCALE_DOWN_CPU", "25"))
        self.up_seconds = float(os.getenv("AUTOSCALE_UP_SECONDS", "60"))
        self.down_seconds = float(os.getenv("AUTOSCALE_DOWN_SECONDS", "300"))
        self.cooldown = float(os.getenv("AUTOSCALE_COOLDOWN", "300"))
        if not (0 < self.down_cpu < self.up_cpu and
                min(self.interval, self.up_seconds, self.down_seconds, self.cooldown) > 0):
            raise ValueError("CPU thresholds must satisfy 0 < down < up; timings must be positive")
        self.reset()
        self.last_change = time.monotonic()

    def reset(self):
        self.high_since = None
        self.low_since = None
        self.last_sample = None

    def decision(self, replicas, total_cpu, now):
        # A gap in valid measurements cannot count as sustained utilization.
        if self.last_sample is not None and now - self.last_sample > self.interval * 3:
            self.reset()
        self.last_sample = now
        if replicas == 1 and total_cpu >= self.up_cpu:
            self.high_since = now if self.high_since is None else self.high_since
        else:
            self.high_since = None
        # Use the SUM across both instances: one remaining instance must handle it.
        if replicas == 2 and total_cpu <= self.down_cpu:
            self.low_since = now if self.low_since is None else self.low_since
        else:
            self.low_since = None
        # Initial scale-up can happen immediately after the high-load window.
        if self.high_since is not None and now - self.high_since >= self.up_seconds:
            if replicas == 1 and now - self.last_change >= self.up_seconds:
                return 2
        if (self.low_since is not None and now - self.low_since >= self.down_seconds
                and now - self.last_change >= self.cooldown):
            return 1
        return None

    def status(self, replicas, total_cpu, now, phase=None):
        seconds_until_action = None
        cooldown_remaining = 0.0

        if replicas == 1 and self.high_since is not None:
            phase = phase or "waiting_scale_up"
            high_window = max(0.0, self.up_seconds - (now - self.high_since))
            change_window = max(0.0, self.up_seconds - (now - self.last_change))
            seconds_until_action = max(high_window, change_window)
        elif replicas == 2:
            cooldown_remaining = max(0.0, self.cooldown - (now - self.last_change))
            if self.low_since is not None:
                phase = phase or "waiting_scale_down"
                low_window = max(0.0, self.down_seconds - (now - self.low_since))
                seconds_until_action = max(low_window, cooldown_remaining)

        return {
            "version": 1,
            "updated_at": time.time(),
            "sampled_at": time.time(),
            "state": phase or "holding",
            "replicas": replicas,
            "max_replicas": 2,
            "cpu_percent": round(total_cpu, 2) if total_cpu is not None else None,
            "scale_up_cpu_percent": self.up_cpu,
            "scale_down_cpu_percent": self.down_cpu,
            "scale_up_seconds": self.up_seconds,
            "scale_down_seconds": self.down_seconds,
            "cooldown_seconds": self.cooldown,
            "cooldown_remaining_seconds": round(cooldown_remaining, 1),
            "seconds_until_action": (round(seconds_until_action, 1)
                                     if seconds_until_action is not None else None),
        }


def write_status(policy, replica_count, total_cpu, now, phase=None):
    atomic_write_status(policy.status(replica_count, total_cpu, now, phase))


def run():
    policy = Policy()
    replica_count = 0
    total_cpu = None
    LOG.info("Automatic Laravel scaling 1–2: up >= %.1f%% for %.0fs; "
             "down combined <= %.1f%% for %.0fs; down cooldown %.0fs",
             policy.up_cpu, policy.up_seconds, policy.down_cpu,
             policy.down_seconds, policy.cooldown)
    while True:
        started = time.monotonic()
        try:
            containers = replicas()
            if not healthy(containers[0]["State"]) or not state(NGINX).get("Running"):
                raise RuntimeError("Primary or Nginx unavailable; suspending scaling")
            ready = [value for value in containers if healthy(value["State"])]
            route(ready)
            if any(value["State"].get("Running") and not healthy(value["State"]) for value in containers):
                raise RuntimeError("Secondary is starting/unhealthy; suspending scaling")
            total_cpu = cpu_usage([value["Name"].lstrip("/") for value in ready])
            replica_count = len(ready)
            now = time.monotonic()
            action = policy.decision(replica_count, total_cpu, now)
            LOG.info("instances=%s combined_cpu=%.2f%% decision=%s", len(ready), total_cpu, action or "hold")
            phase = "scaling_up" if action == 2 else ("scaling_down" if action == 1 else None)
            write_status(policy, replica_count, total_cpu, now, phase)
            if action:
                if action == 2:
                    scale_up()
                else:
                    scale_down()
                policy.last_change = time.monotonic()
                policy.reset()
            heartbeat()
        except Exception:
            policy.reset()
            try:
                write_status(policy, replica_count, total_cpu, time.monotonic(), "error")
            except Exception:
                LOG.exception("Could not write autoscaler error status")
            LOG.exception("Scaling cycle failed; retrying")
        time.sleep(max(1, policy.interval - (time.monotonic() - started)))


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    if sys.argv[1:] == ["health"]:
        try:
            sys.exit(0 if time.time() - float(HEARTBEAT.read_text()) < 90 else 1)
        except (OSError, ValueError):
            sys.exit(1)
    run()
